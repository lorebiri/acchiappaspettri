// Genera i file d'esempio SINTETICI dei tutorial (docs/tutorial/). Nessuno di questi file è una misura reale.
// Synthetic example files for the tutorials. None of these files is a real measurement.
// Uso / usage:  node examples/genera-esempi-sintetici.js
// Il risultato è sempre lo stesso (generatore pseudo-casuale con seme fisso).
const fs=require('fs'), path=require('path');
const out=path.join(__dirname);
function rng(seed){ let s=seed>>>0||1; return ()=>{ s^=s<<13; s>>>=0; s^=s>>>17; s^=s<<5; s>>>=0; return s/4294967296; }; }
function gauss(r){ let u=0,v=0; while(!u)u=r(); while(!v)v=r(); return Math.sqrt(-2*Math.log(u))*Math.cos(2*Math.PI*v); }
function poisson(r, l){ if (l>30) return Math.max(0, Math.round(l+Math.sqrt(l)*gauss(r))); let L=Math.exp(-l), k=0, p=1; do { k++; p*=r(); } while (p>L); return k-1; }
const G=(x,c,w)=>Math.exp(-0.5*((x-c)/w)**2);
const write=(dir,name,txt)=>{ fs.mkdirSync(path.join(out,dir),{recursive:true}); fs.writeFileSync(path.join(out,dir,name),txt); };

/* 1. FTIR: polietilene invecchiato 0–1000 h (ATR, assorbanza) */
{ const r=rng(11), times=[0,100,250,500,750,1000];
  times.forEach(t=>{ const ox=0.42*Math.pow(t/1000,1.5);   // ossidazione con un breve periodo di induzione
    let s='# DATI SINTETICI / SYNTHETIC DATA - non è una misura reale / not a real measurement\n'
         +`# Polietilene invecchiato ${t} h (esempio del tutorial 1) / aged polyethylene ${t} h (tutorial 1 example)\n`
         +'# Generato da / generated by examples/genera-esempi-sintetici.js\n'
         +'Wavenumber (cm-1),Absorbance\n';
    for (let x=4000;x>=600;x-=2){
      let y=0.010+0.000004*(4000-x)
        +1.00*G(x,2915,11)+0.72*G(x,2848,8)+0.30*G(x,1472,4)+0.26*G(x,1462,4)+0.025*G(x,1368,4)+0.20*G(x,730,3)+0.18*G(x,719,3)
        +ox*(0.24*G(x,1714,13)+0.09*G(x,1736,11)+0.035*G(x,1780,10)+0.04*G(x,1176,25)+0.05*G(x,3400,120))
        +0.0008*gauss(r);
      s+=`${x},${y.toFixed(5)}\n`; }
    write('ftir-polietilene-sintetico', `PE_${String(t).padStart(4,'0')}h_SINTETICO.csv`, s); }); }

/* 2. HPLC: 6 standard, bianco, controllo, 2 incogniti (0–10 min, rivelatore UV in mAU) */
{ const r=rng(23), H=11.8;   // mAU per mg/L all'apice
  const set=[['STD1_0,5mgL',0.5],['STD2_1mgL',1],['STD3_2mgL',2],['STD4_5mgL',5],['STD5_10mgL',10],['STD6_20mgL',20],['BIANCO',0],['CONTROLLO_8mgL',8],['INCOGNITO_A',3.7],['INCOGNITO_B',12.4]];
  set.forEach(([nm,c],k)=>{ const inj=1+0.006*gauss(r), rt=4.20+0.004*gauss(r), mat=/INCOGNITO/.test(nm);
    let s='# DATI SINTETICI / SYNTHETIC DATA - non è una misura reale / not a real measurement\n'
         +`# Cromatogramma d'esempio del tutorial 2 / tutorial 2 example chromatogram: ${nm.replace(/_/g,' ')}\n`
         +'# Generato da / generated by examples/genera-esempi-sintetici.js\n'
         +'Time (min),Signal (mAU)\n';
    for (let i=0;i<=2000;i++){ const x=i*0.005;
      let y=0.4+0.08*x
        +6*G(x,1.05,0.05)-2.5*G(x,1.22,0.06)            // fronte del solvente
        +H*c*inj*G(x,rt,0.045)                            // analita a 4,2 min
        +(mat?18*G(x,6.35,0.06)+7*G(x,2.6,0.05):0)        // altri composti della matrice, lontani dall'analita
        +0.12*gauss(r);
      s+=`${x.toFixed(3)},${y.toFixed(3)}\n`; }
    write('hplc-taratura-sintetico', `${String(k+1).padStart(2,'0')}_${nm}_SINTETICO.csv`, s); }); }

/* 3. XRF: lega di rame (bronzo al piombo), tubo Rh 40 kV, spettro calcolato con il modello FP del programma */
// eval: carica il nucleo di calcolo dal file index.html di questo stesso repository, come fa test/xrf-fp-benchmark.js
{ const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
  eval(html.slice(html.indexOf('/*CORE-START*/'), html.indexOf('/*CORE-END*/'))+';global.C={fpTau,fpCompton,fpSetup,fpIntensities,fpLineE,FP,xrfFWHM}');
  const escSi=E=>{ if (E<1.9) return 0; const mi=C.fpTau('Si',E), mk=C.fpTau('Si',1.74); return 0.5*0.047*(1-1/10.4)*(1-(mk/mi)*Math.log(1+mi/mk)); };
  const comp={Cu:0.840, Sn:0.080, Pb:0.050, Zn:0.025, As:0.005}, els=Object.keys(comp), r=rng(37), peakCounts=6e4;
  const S=C.fpSetup({anode:'Rh', kv:40, psi1:45, psi2:45, d1:1, d2:1}), layers=[{comp, t:Infinity}];
  const xs=new Float64Array(2048).map((_,i)=>0.02*i), ys=new Float64Array(xs.length), lines=[];
  els.forEach(e=>{ for (const l of ['Ka','Kb','La','Lb']) if (C.fpLineE(e,l)) lines.push([e,l]); });
  const I=C.fpIntensities(layers, S, lines);
  const add=(E, A, fw)=>{ const sg=fw/2.3548; for (let i=0;i<xs.length;i++){ const d=xs[i]-E; if (Math.abs(d)<5*sg) ys[i]+=A*0.02*Math.exp(-0.5*(d/sg)**2)/(sg*2.5066); } };
  const peaks=[];
  els.forEach(e=>{ const F=C.FP.el[e].fam;
    for (const fam of ['K','L']){ if (!F[fam]) continue; const main=fam==='K'?'Ka':'La', Imain=I[e+' '+main]||0; if (!Imain) continue; const relMain=F[fam].find(x=>x[0]===main)[2];
      F[fam].forEach(([nm,E,rel])=>{ let A=Imain*rel/relMain; if (nm==='Kb') A=I[e+' Kb']||A; if (nm==='Lb1'||nm==='Lb2'||nm==='Lg1'||nm==='Ln'){ const tb=F.L.filter(x=>x[0].startsWith('Lb')).reduce((t,x)=>t+x[2],0); A=(I[e+' Lb']||0)*rel/tb; }
        if (E>0.9) peaks.push([E,A]); }); } });
  const mx=Math.max(...peaks.map(p=>p[1])), sc=peakCounts/mx;
  peaks.forEach(([E,A])=>{ add(E, A*sc, C.xrfFWHM(E)); const es=escSi(E); if (es>0) add(E-1.74, A*sc*es, C.xrfFWHM(E-1.74)); });
  const T=C.FP.el[S.anode].fam.K, th=(S.psi1+S.psi2)*Math.PI/180, IC=C.fpCompton(comp, S)*sc, relKa=T.find(x=>x[0]==='Ka')[2];
  T.forEach(([nm,E,rel])=>{ add(E, IC*0.3*rel/relKa, C.xrfFWHM(E)); add(E/(1+E/511*(1-Math.cos(th))), IC*rel/relKa, Math.hypot(C.xrfFWHM(E), 0.35)); });
  for (let i=0;i<xs.length;i++){ const x=xs[i]; const b=peakCounts*2e-4*(x>1.5? Math.exp(-(((x-12)/9)**2))+0.3 : 0.2); ys[i]=i<20?0:poisson(r, ys[i]+b); }
  let s='# DATI SINTETICI / SYNTHETIC DATA - not a real measurement\n# Sample: bronzo al piombo simulato / simulated leaded bronze (tutorial 3)\n'
       +'# Generated by: examples/genera-esempi-sintetici.js (FP model of Acchiappaspettri)\n'
       +'# Tube Anode: Rh\n# Tube Voltage: 40\n# Incident beam angle: 45\n# Fluorescence beam: 45\n# MCA Channels: 2048\n# Calibration1: 0 0\n# Calibration2: 2047 40,94\n#\n';
  for (let i=0;i<2048;i++) s+=ys[i]+'\n';
  write('xrf-lega-sintetico', 'BRONZO_SIMULATO_Rh40kV_SINTETICO.mca', s); }
console.log('Esempi sintetici scritti in', out);
